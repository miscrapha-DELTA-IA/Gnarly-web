 assert.match(front,/aria-selected="true"/);
 assert.match(front,/50%/);
 const stems=renderMusicPanel({...state,tab:'stems',stemLevels:{vocal:.6,drums:1,bass:1,other:1},stemStatus:'GPU real',stemsReady:true});
